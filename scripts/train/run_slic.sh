# step x G = 8 branches, 4 turns per episode (env.max_steps; the paper's runs trained with env.max_steps=8), online
# continuation (random), separate validity / performance advantage normalisation, ngspice. Every configs/train/*.yaml differs from this command only by hydra overrides; `slic train --config` runs the
